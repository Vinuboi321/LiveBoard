const assert = require('node:assert/strict');
const Module = require('node:module');
const { buildSync } = require('esbuild');
const m = new Module('anchors', module); m.paths = module.paths;
m._compile(buildSync({ entryPoints: ['src/teacher/anchors.ts'], bundle: true, platform: 'node', format: 'cjs', write: false }).outputFiles[0].text, 'anchors.cjs');
const { dragRect, union, graphicRects } = m.exports;
assert.deepEqual(dragRect({x:.8,y:.7},{x:.2,y:.1}), {x:.2,y:.1,width:.6000000000000001,height:.6});
assert.deepEqual(dragRect({x:-.1,y:0},{x:1.2,y:1}), {x:0,y:0,width:1,height:1});
assert.deepEqual(union([{x:.1,y:.2,width:.2,height:.1},{x:.1,y:.4,width:.4,height:.1}]), {x:.1,y:.2,width:.4,height:.3});
const OPS = {save:1,restore:2,transform:3,paintImageXObject:4,paintInlineImageXObject:5,paintImageMaskXObject:6,constructPath:7,paintFormXObjectBegin:8,paintFormXObjectEnd:9};
const viewport = { transform: [1,0,0,-1,0,1000], width:1000,height:1000 };
const list = {fnArray:[1,3,4,2,1,3,4,2],argsArray:[[],[200,0,0,100,100,200],['image1'],[],[],[100,0,0,200,600,400],['image2'],[]]};
assert.deepEqual(graphicRects(list,OPS,viewport), [{x:.1,y:.7,width:.19999999999999998,height:.10000000000000009},{x:.6,y:.4,width:.09999999999999998,height:.19999999999999996}]);
const rotated = graphicRects({fnArray:[3,4],argsArray:[[0,100,-200,0,400,300],['image']]},OPS,viewport);
assert(Math.abs(rotated[0].x-.2)<1e-10 && Math.abs(rotated[0].y-.6)<1e-10 && Math.abs(rotated[0].width-.2)<1e-10);
const bars = graphicRects({fnArray:[7,7],argsArray:[[[],[],[100,100,200,130]],[[],[],[200,100,300,130]]]},OPS,viewport);
assert.equal(bars.length,1); assert(Math.abs(bars[0].width-.2)<1e-10);
assert.equal(graphicRects({fnArray:[7],argsArray:[[[],[],[0,0,1000,0]]]},OPS,viewport).length,0);
console.log('PASS: drag direction/clamping, multiline unions, transformed PDF image bounds, rotation, diagram merging, zero-area exclusion.');
